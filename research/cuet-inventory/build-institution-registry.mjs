const typeLabels = {
  Central: 'Central University',
  State: 'State University',
  Deemed: 'Deemed University',
  Private: 'Private University',
  OtherGovernment: 'Other Government Institution',
};

const institutions = Object.entries(names).flatMap(([type, values]) => values.map((name, index) => {
  const source = sources[type];
  const id = `${type.toLowerCase().replace(/[^a-z]+/g, '-')}-${String(index + 1).padStart(3, '0')}`;
  return {
    institutionId: id,
    name,
    ntaType: typeLabels[type],
    ntaParticipatingYear: admissionYear,
    collegeCount: null,
    programmeCount: null,
    participationVerification: {
      status: 'verified',
      admissionYear,
      lastVerified,
      source: { ...source, admissionYear, lastVerified, verificationStatus: 'verified' },
    },
    collegeProgrammeCoverage: {
      status: 'incomplete',
      note: 'NTA participation is verified; constituent-college, campus, programme, seat, counselling, and cutoff documents require institution-specific verification.',
    },
  };
}));

const counts = Object.fromEntries(Object.entries(names).map(([type, values]) => [type, values.length]));
const expected = { Central: 49, State: 41, Deemed: 27, Private: 120, OtherGovernment: 7 };
for (const [type, count] of Object.entries(expected)) {
  if (counts[type] !== count) throw new Error(`${type} count mismatch: ${counts[type]} !== ${count}`);
}
if (institutions.length !== 244) throw new Error(`Total count mismatch: ${institutions.length} !== 244`);

const outputDir = path.resolve('research/cuet-inventory');
fs.mkdirSync(outputDir, { recursive: true });
const payload = {
  schemaVersion: '1.0.0',
  inventoryType: 'NTA participating institution registry',
  admissionYear,
  lastVerified,
  counts: { ...counts, total: institutions.length },
  source: {
    url: 'https://cuet.nta.nic.in/participating-universities/',
    documentTitle: 'Participating Universities - CUET (UG)',
    pageOrSection: 'Participating Universities index',
    admissionYear,
    lastVerified,
    verificationStatus: 'verified',
  },
  institutions,
};
fs.writeFileSync(path.join(outputDir, 'institution-registry.json'), `${JSON.stringify(payload, null, 2)}\n`);

const csvFields = ['institutionId', 'name', 'ntaType', 'ntaParticipatingYear', 'participationStatus', 'collegeProgrammeCoverageStatus', 'sourceUrl', 'sourceDocumentTitle', 'sourcePageOrSection', 'admissionYear', 'lastVerified'];
const csvEscape = value => `"${String(value ?? '').replaceAll('"', '""')}"`;
const csv = [csvFields.join(','), ...institutions.map(item => [
  item.institutionId, item.name, item.ntaType, item.ntaParticipatingYear,
  item.participationVerification.status, item.collegeProgrammeCoverage.status,
  item.participationVerification.source.url, item.participationVerification.source.documentTitle,
  item.participationVerification.source.pageOrSection, item.participationVerification.source.admissionYear,
  item.participationVerification.source.lastVerified,
].map(csvEscape).join(','))].join('\n');
fs.writeFileSync(path.join(outputDir, 'institution-registry.csv'), `${csv}\n`);
